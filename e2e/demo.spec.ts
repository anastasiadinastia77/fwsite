import { test, expect } from '@playwright/test';
test('полный демо-заказ без отправки данных',async({page})=>{
 const outgoing:string[]=[];
 page.on('request',r=>{if(r.method()==='POST'||!r.url().startsWith('http://127.0.0.1:5173'))outgoing.push(r.url());});
 await page.goto('/');
 await page.getByRole('button',{name:'Indie Dance',exact:true}).click();
 await expect(page.locator('.expert-card')).toHaveCount(1);
 await page.getByRole('button',{name:'Подробнее',exact:true}).click();
 await expect(page.getByRole('dialog')).toContainText('Вымышленный профиль');
 await page.getByRole('button',{name:'Выбрать разбор'}).click();
 await expect(page.locator('input[type=file]')).toHaveCount(0);
 await page.getByLabel('Псевдоним').fill('Demo Artist');
 await page.getByLabel('Название трека').fill('Afterhours');
 await page.getByLabel('Тестовый контакт').fill('@demo');
 await page.getByRole('button',{name:'Симулировать оплату'}).click();
 await expect(page.getByText('Демо-оплата подтверждена',{exact:true})).toBeVisible();
 await page.locator('input[type=file]').setInputFiles({name:'demo.mp3',mimeType:'audio/mpeg',buffer:Buffer.from('demo')});
 await page.getByRole('button',{name:'Симулировать передачу'}).click();
 await page.getByRole('button',{name:'Симулировать голосовой'}).click();
 await page.getByLabel('Вопрос 1').fill('Что изменить в аранжировке?');
 await page.getByRole('button',{name:'Симулировать отправку'}).click();
 await expect(page.getByText('Раунд использован')).toBeVisible();
 await expect(page.locator('textarea')).toHaveCount(0);
 await page.getByRole('button',{name:'Показать демо-ответ'}).click();
 await expect(page.getByText('Один раунд уточнений завершён.')).toBeVisible();
 await page.getByRole('button',{name:'Посмотреть возможности'}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 expect(outgoing).toEqual([]);
});
